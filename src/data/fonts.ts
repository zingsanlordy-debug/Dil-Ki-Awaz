// ============================================================================
// TRANSFORM SHAYARI LINE
// Golden Rule 1: 'en-normal' / default returns plain line untouched
// Golden Rule 2: User selection transforms text
// ============================================================================
export function transformShayariLine(line: string, fontId: string): string {
  if (!line) return line;

  switch (fontId) {
    // 1. NORMAL - Plain text untouched
    case 'en-normal':
    case 'normal':
      return line;

    // 2. SMALL CAPS - Lᴏᴠᴇ
    case 'en-small-caps':
    case 'en-upper-small':
    case 'upper-small':
      return line.split('').map((ch) => SMALL_CAPS_MAP[ch.toLowerCase()] || ch).join('');

    // 3. WIDE AESTHETIC - L O V E
    case 'en-wide':
      return line.split('').map((ch) => (ch === ' ' ? '   ' : ch)).join(' ');

    // 4. BOLD STYLISH - 𝐋𝐎𝐕𝐄
    case 'en-bold-stylish':
      return line.split('').map((ch) => BOLD_SERIF_MAP[ch] || ch).join('');

    // 5. ITALIC SANS - 𝘓𝘖𝘝𝘌
    case 'en-italic-sans':
      return line.split('').map((ch) => ITALIC_SANS_MAP[ch] || ch).join('');

    // 6. BOLD SANS - Seedha Bold (dusra -> 𝐝𝐮𝐬𝐫𝐚 / 𝗱𝘂𝘀𝗿𝗮)
    case 'en-bold-sans':
      return line.split('').map((ch) => BOLD_SANS_MAP[ch] || ch).join('');

    // 7. CURSIVE SCRIPT - 𝓛𝓸𝓿𝓮
    case 'en-cursive-script':
    case 'en-fancy-cursive':
    case 'fancy-cursive':
      return line.split('').map((ch) => BOLD_SCRIPT_MAP[ch] || ch).join('');

    // 8. GOTHIC FRAKTUR - 𝔏𝔬𝔳𝔢
    case 'en-gothic-fraktur':
      return line.split('').map((ch) => OLD_ENGLISH_MAP[ch] || ch).join('');

    // 9. DOUBLE STRUCK - 𝕃𝕆𝕍𝔼
    case 'en-double-struck':
    case 'en-double':
    case 'double':
      return line.split('').map((ch) => DOUBLE_MAP[ch] || ch).join('');

    // 10. MONOSPACE - 𝙻𝙾𝚅𝙴
    case 'en-monospace':
      return line.split('').map((ch) => TYPEWRITER_MAP[ch] || ch).join('');

    // 11. CIRCLED - ⓁⓄⓋⒺ
    case 'en-circled':
    case 'en-circle':
    case 'circle':
      return line.split('').map((ch) => CIRCLE_MAP[ch] || ch).join('');

    // 12. CIRCLED DARK - 🅻🅾🆅🅴
    case 'en-circled-dark':
      return line.split('').map((ch) => CIRCLED_DARK_MAP[ch] || ch).join('');

    // 13. SQUARED CAPS - 🄻🄾🅅🄴
    case 'en-squared-caps':
    case 'en-boxed':
    case 'boxed':
      return line.split('').map((ch) => SQUARED_CAPS_MAP[ch] || ch).join('');

    // 14. PARENTHESIZED - ⒧⒪⒱⒠
    case 'en-parenthesized':
      return line.split('').map((ch) => PAREN_MAP[ch] || ch).join('');

    // 15. FULLWIDTH - ＬＯ𝐕Ｅ
    case 'en-fullwidth':
      return line.split('').map((ch) => FULLWIDTH_MAP[ch] || ch).join('');

    // 16. SUPERSCRIPT - ᴸᴼⱽᴱ
    case 'en-superscript':
      return line.split('').map((ch) => SUPERSCRIPT_MAP[ch] || ch).join('');

    // 17. SUBSCRIPT - Lₒᵥₑ
    case 'en-subscript':
      return line.split('').map((ch) => SUBSCRIPT_MAP[ch] || ch).join('');

    // 18. NINJA BRACKETS - 〚 L O V E 〛
    case 'en-ninja-brackets':
      return `〚 ${line} 〛`;

    // 19. STARS - ★彡[ LOVE ]彡★
    case 'en-stars':
      return `★彡[ ${line} ]彡★`;

    // 20. HEARTS - ♡ LOVE ♡
    case 'en-hearts':
      return `♡ ${line} ♡`;

    // 21. UPSIDE DOWN - ƎΛO˥
    case 'en-upside-down':
      return line
        .split('')
        .reverse()
        .map((ch) => UPSIDE_DOWN_MAP[ch] || ch)
        .join('');

    // 22. WAVE EFFECT - Lövë
    case 'en-wave':
      return line.split('').map((ch) => WAVE_MAP[ch] || ch).join('');

    // 23. BUBBLE JOIN - Lₒₒᵥᵥₑₑ
    case 'en-bubble-join':
      return line
        .split('')
        .map((ch) => {
          if (ch === ' ') return ' ';
          const sub = SUBSCRIPT_MAP[ch] || ch;
          return `${ch}${sub}`;
        })
        .join('');

    // 24. ZALGO / GLITCH - L̷o̷v̷e̷
    case 'en-zalgo':
    case 'en-glitch':
    case 'glitch':
      return line
        .split('')
        .map((ch) => (ch === ' ' ? ' ' : `${ch}\u0337`))
        .join('');

    // 25. REGIONAL / FLAG (Green Box Letters: 🇱 🇴 🇻 🇪 - User Most Important)
    case 'en-regional-flag':
      return line
        .split('')
        .map((ch) => REGIONAL_FLAG_MAP[ch] || (ch === ' ' ? '   ' : ch))
        .join(' ');

    // 26. BOLD SERIF - 𝐋𝐎𝐕𝐄
    case 'en-bold-serif':
      return line.split('').map((ch) => BOLD_SERIF_MAP[ch] || ch).join('');

    // 27. TYPEWRITER - 𝙻𝙾𝚅𝙴
    case 'en-typewriter':
    case 'typewriter':
      return line.split('').map((ch) => TYPEWRITER_MAP[ch] || ch).join('');

    // 28. OLD ENGLISH - 𝔏𝔬𝔳𝔢
    case 'en-old-english':
    case 'old-english':
      return line.split('').map((ch) => OLD_ENGLISH_MAP[ch] || ch).join('');

    // 29. GREEK STYLE - Lσvε
    case 'en-greek':
      return line.split('').map((ch) => GREEK_MAP[ch] || ch).join('');

    // 30. CHEROKEE - ᏞᎾᏙᎬ
    case 'en-cherokee':
      return line.split('').map((ch) => CHEROKEE_MAP[ch] || ch).join('');

    // 31. FANCY UNDERLINE - L̲o̲v̲e̲
    case 'en-underline':
      return line
        .split('')
        .map((ch) => (ch === ' ' ? ' ' : `${ch}\u0332`))
        .join('');

    // 32. STRIKE THROUGH - L̶o̶v̶e̶
    case 'en-strike':
    case 'strike':
      return line
        .split('')
        .map((ch) => (ch === ' ' ? ' ' : `${ch}\u0336`))
        .join('');

    // 33. DOUBLE UNDERLINE - L͇o͇v͇e͇
    case 'en-double-underline':
      return line
        .split('')
        .map((ch) => (ch === ' ' ? ' ' : `${ch}\u0347`))
        .join('');

    // 34. SPARKLE - ✨ LOVE ✨
    case 'en-sparkle':
      return `✨ ${line} ✨`;

    // Legacy fallback aliases
    case 'en-signature':
    case 'signature':
      return line.split('').map((ch) => BOLD_SCRIPT_MAP[ch] || ch).join('');

    default:
      return line;
  }
}
